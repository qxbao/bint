// asHuman/asAgent đặt biến môi trường mà Bint dùng để nhận biết phiên agent. Tiến
// trình kiểm thử có thể đang chạy trong một phiên agent thật nên phải xoá hết.
func asHuman(t *testing.T) {
	for _, k := range []string{"BINT_AGENT", "CLAUDECODE", "AI_AGENT", "CODEX_SANDBOX", "CODEX_SANDBOX_NETWORK_DISABLED", "GEMINI_CLI"} {
		t.Setenv(k, "")
	}
}

func asAgent(t *testing.T) {
	asHuman(t)
	t.Setenv("BINT_AGENT", "1")
}

func TestKnowledgeEndToEnd(t *testing.T) {
	testutil.Isolate(t)
	asHuman(t)
	root := testutil.NewRepo(t, map[string]string{
		"go.mod":            "module demo\n",
		"internal/db/db.go": "package db\n\n// Code generated by sqlc. DO NOT EDIT.\n\nfunc Open() {}\n",
		"Makefile":          "gen:\n\tsqlc generate\n\ntest:\n\tgo test ./...\n",
		"AGENTS.md":         "# Ghi chú của nhóm\n\nGiữ nguyên đoạn này.\n",
	})
	testutil.Git(t, root, "config", "user.name", "Rev")
	testutil.Git(t, root, "config", "user.email", "rev@example.com")

	out, code := run(t, root, "", "init", "--no-hooks")
	if code != 0 || !strings.Contains(out, "skill b-bootstrap") {
		t.Fatalf("init: %d\n%s", code, out)
	}
	skill, err := os.ReadFile(filepath.Join(root, ".claude", "skills", "b-bootstrap", "SKILL.md"))
	if err != nil || !strings.Contains(string(skill), "name: b-bootstrap") {
		t.Fatalf("skill: %v", err)
	}
	if lock, err := os.ReadFile(filepath.Join(root, ".bint", "skills", "core.lock")); err != nil || !strings.Contains(string(lock), "b-bootstrap") {
		t.Fatalf("core.lock: %v %s", err, lock)
	}

	// Static discovery.
	out, code = run(t, root, "", "bootstrap", "--json")
	var rep struct {
		Generated []struct{ Dir string }  `json:"generated"`
		Commands  []struct{ Name string } `json:"commands"`
		Knowledge []any                   `json:"existing_knowledge"`
	}
	if code != 0 || json.Unmarshal([]byte(out), &rep) != nil || len(rep.Generated) != 1 || rep.Generated[0].Dir != "internal/db" || rep.Knowledge == nil {
		t.Fatalf("bootstrap --json: %d\n%s", code, out)
	}
	if !strings.Contains(out, `"make:gen"`) {
		t.Fatalf("thiếu lệnh Makefile:\n%s", out)
	}

	// Agent ghi mục: candidate; không qua kiểm tra thì không được ghi.
	asAgent(t)
	out, code = run(t, root, "Tệp trong internal/db được sinh bởi sqlc.\nSửa query rồi chạy `make gen`.\n",
		"knowledge", "add", "--type", "rule", "--title", "Không sửa tay internal/db; chạy make gen",
		"--paths", "internal/db/**", "--evidence", "internal/db/db.go:3#DO", "--evidence", "Makefile:1-2",
		"--input", "Makefile", "--json", "-")
	var added struct {
		Saved  bool   `json:"saved"`
		ID     string `json:"id"`
		Status string `json:"status"`
		Origin string `json:"origin"`
	}
	if code != 0 || json.Unmarshal([]byte(out), &added) != nil || !added.Saved || added.Status != "candidate" || added.Origin != "agent" {
		t.Fatalf("agent add: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "knowledge", "add", "--type", "warning", "--evidence", "nope.go:1", "x y z"); code != 1 || !strings.Contains(out, "không qua kiểm tra") {
		t.Fatalf("add bằng chứng sai: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "knowledge", "add", "--type", "warning", "--origin", "human", "x"); code == 0 || !strings.Contains(out, "origin: human") {
		t.Fatalf("agent giả làm người: %d\n%s", code, out)
	}
	for _, args := range [][]string{{"knowledge", "approve", added.ID}, {"knowledge", "review"}, {"knowledge", "verify", "--apply"},
		{"knowledge", "reject", added.ID, "--reason", "x"}} {
		if out, code := run(t, root, "", args...); code == 0 || !strings.Contains(out, "phiên agent") {
			t.Fatalf("%v trong phiên agent: %d\n%s", args, code, out)
		}
	}

	// Người duyệt qua review (stdin), rồi ghi một điểm dễ sai của chính mình.
	asHuman(t)
	if out, code := run(t, root, "", "knowledge", "verify"); code != 0 || !strings.Contains(out, "1 mục, 0 lỗi") {
		t.Fatalf("verify: %d\n%s", code, out)
	}
	out, code = run(t, root, "a\n", "knowledge", "review")
	if code != 0 || !strings.Contains(out, "candidate → verified") || !strings.Contains(out, "sqlc generate") {
		t.Fatalf("review: %d\n%s", code, out)
	}
	item, _ := os.ReadFile(filepath.Join(root, ".bint", "knowledge", "items", added.ID+".md"))
	if !strings.Contains(string(item), "reviewed_by: Rev <rev@example.com>") || !strings.Contains(string(item), "status: verified") {
		t.Fatalf("tệp sau khi duyệt:\n%s", item)
	}
	out, code = run(t, root, "", "knowledge", "add", "--type", "warning", "--paths", "internal/db", "Open() không an toàn khi gọi song song")
	if code != 0 || !strings.Contains(out, "warning/verified, origin human") {
		t.Fatalf("human add: %d\n%s", code, out)
	}

	// Xuất bản AGENTS.md: không terminal → chỉ xem trước.
	out, code = run(t, root, "", "bootstrap", "publish")
	if code != 0 || !strings.Contains(out, "+ - **Không sửa tay internal/db") || !strings.Contains(out, "chưa ghi") {
		t.Fatalf("publish xem trước: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "bootstrap", "publish", "--yes"); code != 0 {
		t.Fatalf("publish: %d\n%s", code, out)
	}
	agents, _ := os.ReadFile(filepath.Join(root, "AGENTS.md"))
	claudeMD, _ := os.ReadFile(filepath.Join(root, "CLAUDE.md"))
	if !strings.Contains(string(agents), "Giữ nguyên đoạn này.") || !strings.Contains(string(agents), "[k:"+added.ID+"]") ||
		!strings.Contains(string(agents), "### Điểm dễ sai") || !strings.Contains(string(claudeMD), "@AGENTS.md") {
		t.Fatalf("AGENTS.md:\n%s\nCLAUDE.md:\n%s", agents, claudeMD)
	}
	if out, code := run(t, root, "", "bootstrap", "publish", "--yes"); code != 0 || !strings.Contains(out, "không có thay đổi") {
		t.Fatalf("publish lần hai phải không đổi: %d\n%s", code, out)
	}
	// Sửa tay khối bint → xung đột, không ghi đè.
	os.WriteFile(filepath.Join(root, "AGENTS.md"), []byte(strings.Replace(string(agents), "Điểm dễ sai", "Sửa tay", 1)), 0o644)
	if out, code := run(t, root, "", "bootstrap", "publish", "--yes"); code != 1 || !strings.Contains(out, "xung đột") {
		t.Fatalf("publish khi khối bị sửa: %d\n%s", code, out)
	}

	// Bằng chứng đổi → verify --apply chuyển stale; approve --refresh khôi phục.
	os.WriteFile(filepath.Join(root, "Makefile"), []byte("gen:\n\tsqlc generate --strict\n"), 0o644)
	if out, code := run(t, root, "", "knowledge", "verify", "--apply"); code != 1 || !strings.Contains(out, "verified → stale") {
		t.Fatalf("verify --apply: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "knowledge", "approve", added.ID); code != 1 || !strings.Contains(out, "--refresh") {
		t.Fatalf("approve stale: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "knowledge", "approve", "--refresh", added.ID[len(added.ID)-6:]); code != 0 || !strings.Contains(out, "stale → verified") {
		t.Fatalf("approve --refresh: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "knowledge", "list"); code != 0 || !strings.Contains(out, "verified=2") {
		t.Fatalf("list: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "doctor"); !strings.Contains(out, "tri thức") || !strings.Contains(out, "skill b-bootstrap") {
		t.Fatalf("doctor: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "knowledge", "search", "x"); code != 0 {
		t.Fatalf("search: %d\n%s", code, out)
	}
}

// Đo nhánh minimal dựng từ tri thức: eval bootstrap (agent giả gọi bint thật) tạo
// ảnh chụp tại commit gốc; eval run nhánh minimal strict đặt AGENTS.md từ ảnh chụp.
func TestEvalMinimalFromBootstrapSnapshot(t *testing.T) {
	needShell(t)
	testutil.Isolate(t)
	asHuman(t)
	calc := "add() { echo $(($1 + $2)); }\n"
	root := testutil.NewRepo(t, map[string]string{
		"lib/calc.sh":       calc,
		"tests/run.sh":      "set -e\nfor f in tests/test_*.sh; do sh \"$f\"; done\n",
		"tests/test_add.sh": ". lib/calc.sh\n[ \"$(add 2 3)\" = 5 ]\n",
	})
	good := gitCommit(t, root, "Add a multiplication helper to the calc library\n\nCallers need products, not only sums.",
		map[string]string{"lib/calc.sh": calc + "mul() { echo $(($1 * $2)); }\n", "tests/test_mul.sh": ". lib/calc.sh\n[ \"$(mul 4 5)\" = 20 ]\n"})
	id := "c" + good[:12]
	testutil.Git(t, root, "config", "user.name", "t")
	testutil.Git(t, root, "config", "user.email", "t@example.com")
	if out, code := run(t, root, "", "init", "--no-hooks"); code != 0 {
		t.Fatalf("init: %d\n%s", code, out)
	}
	os.WriteFile(filepath.Join(root, ".bint", "local.yml"), []byte("eval:\n  test_command: \"sh tests/run.sh\"\n  mine:\n    min_source_lines: 1\n"), 0o644)
	if out, code := run(t, root, "", "eval", "mine", "--verify", "--verify-runs", "1"); code != 0 {
		t.Fatalf("mine: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "eval", "approve", id); code != 0 {
		t.Fatalf("approve: %d\n%s", code, out)
	}

	// Chưa có ảnh chụp: nhánh minimal strict bị bỏ qua (skipped), không lỗi.
	noop := filepath.Join(t.TempDir(), "noop.sh")
	os.WriteFile(noop, []byte("true\n"), 0o644)
	out, code := run(t, root, "", "eval", "run", "--arms", "minimal", "--repeats", "1", "--yes", "--agent-command", "sh "+filepath.ToSlash(noop))
	if code != 0 || !strings.Contains(out, "skipped") {
		t.Fatalf("run khi chưa có ảnh chụp: %d\n%s", code, out)
	}

	// Agent bootstrap giả: gọi `bint knowledge add` thật (bint có trong PATH, BINT_AGENT=1).
	boot := filepath.Join(t.TempDir(), "boot.sh")
	os.WriteFile(boot, []byte(`set -e
bint knowledge add --type rule --title "Hàm số học viết trong lib/calc.sh" --evidence lib/calc.sh:1#add "Thêm hàm số học mới vào lib/calc.sh, dạng shell function."
`), 0o644)
	out, code = run(t, root, "", "eval", "bootstrap", "--yes", "--agent-command", "sh "+filepath.ToSlash(boot))
	if code != 0 || !strings.Contains(out, "✓ 1 mục") {
		t.Fatalf("eval bootstrap: %d\n%s", code, out)
	}
	if out, code := run(t, root, "", "eval", "bootstrap", "--list"); code != 0 || !strings.Contains(out, "có") {
		t.Fatalf("eval bootstrap --list: %d\n%s", code, out)
	}

	// Agent đánh giá giả: chỉ giải được khi AGENTS.md có quy tắc từ ảnh chụp.
	agent := filepath.Join(t.TempDir(), "agent.sh")
	os.WriteFile(agent, []byte(`grep -q "Hàm số học viết trong lib/calc.sh" AGENTS.md && echo 'mul() { echo $(($1 * $2)); }' >> lib/calc.sh
echo '{"type":"result","num_turns":1,"total_cost_usd":0.01}'
`), 0o644)
	out, code = run(t, root, "", "eval", "run", "--arms", "none,minimal", "--repeats", "1", "--yes", "--seed", "1",
		"--agent-command", "sh "+filepath.ToSlash(agent))
	if code != 0 || !strings.Contains(out, "completed, 2/2") {
		t.Fatalf("run: %d\n%s", code, out)
	}
	if !strings.Contains(out, "minimal #1  passed") || !strings.Contains(out, "none    #1  failed") {
		t.Fatalf("nhánh minimal phải có tri thức, nhánh none thì không:\n%s", out)
	}
}

func needShell(t *testing.T) {
	t.Helper()
	if _, err := lookSh(); err != nil {
		t.Skip("cần sh")
	}
}

func lookSh() (string, error) { return exec.LookPath("sh") }
